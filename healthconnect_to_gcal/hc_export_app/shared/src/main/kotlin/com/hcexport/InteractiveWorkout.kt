package com.hcexport

import org.json.JSONArray
import org.json.JSONObject
import java.util.Locale

/** The kind of number/text a user can enter for a set. */
enum class MetricKind(val key: String, val label: String) {
    WEIGHT("weight", "Weight"),
    REPS("reps", "Reps"),
    TIME("time", "Time"),
    DISTANCE("distance", "Distance"),
    CALORIES("calories", "Calories"),
    ROUNDS("rounds", "Rounds"),
    CHECK("check", "Done"),
    TEXT("text", "Note");

    companion object {
        fun fromKey(key: String?): MetricKind {
            val normalized = key?.trim()?.lowercase(Locale.US).orEmpty()
            return when (normalized) {
                "weight", "load", "kg", "lbs" -> WEIGHT
                "reps", "rep" -> REPS
                "time", "duration", "seconds", "minutes" -> TIME
                "distance", "distance_m", "meters" -> DISTANCE
                "calories", "cal", "cals" -> CALORIES
                "rounds", "round" -> ROUNDS
                "check", "done", "complete", "completed", "checkbox" -> CHECK
                "text", "note", "notes" -> TEXT
                else -> entries.firstOrNull { it.key == normalized } ?: TEXT
            }
        }
    }
}

data class MetricDef(
    val key: String,
    val label: String,
    val kind: MetricKind,
    val unit: String = "",
    /** Prescribed load guidance from the workout text ("70% of 1RM", "20–32 kg"). */
    val hint: String = "",
)

data class InteractiveSet(
    val label: String = "",
    val target: String = "",
    val metrics: List<MetricDef> = emptyList(),
)

data class InteractiveExercise(
    val name: String,
    val notes: String = "",
    val metrics: List<MetricDef> = emptyList(),
    val sets: List<InteractiveSet> = emptyList(),
)

/** One movement inside a round; a round repeats several of them together. */
data class InteractiveMovement(
    val name: String,
    val target: String = "",
    val notes: String = "",
    val metrics: List<MetricDef> = emptyList(),
)

data class InteractiveRound(
    val label: String = "",
    val notes: String = "",
    val movements: List<InteractiveMovement> = emptyList(),
)

data class InteractiveSection(
    val title: String,
    val kind: String = "other",
    val notes: String = "",
    val metrics: List<MetricDef> = emptyList(),
    val exercises: List<InteractiveExercise> = emptyList(),
    val rounds: List<InteractiveRound> = emptyList(),
) {
    /**
     * Whether the section carries a result of its own. Only a piece scored as a
     * whole — For Time, AMRAP rounds, a benchmark score — does; strength and
     * accessory work is scored set by set. A plan generated before this rule
     * may hold an empty "Total time" on a strength section: [entered] keeps it
     * visible when the user actually filled it in.
     */
    fun showsSectionResult(entered: Boolean): Boolean {
        if (entered) return true
        return when (kind) {
            "strength", "accessory", "rest" -> false
            else -> true
        }
    }
}

/**
 * A structured, editable plan generated by Claude from a workout's text.
 *
 * Keys for user results are positional and stable for a given plan:
 *   section:  "s:<sectionIndex>"
 *   set:      "e:<sectionIndex>:<exerciseIndex>:<setIndex>"
 */
data class InteractivePlan(
    val title: String,
    val summary: String = "",
    val sections: List<InteractiveSection>,
) {
    val isEmpty: Boolean
        get() = sections.all { section ->
            section.exercises.isEmpty() &&
                section.rounds.isEmpty() &&
                section.metrics.isEmpty() &&
                section.notes.isBlank()
        }

    fun toJson(): JSONObject = JSONObject().apply {
        put("title", title)
        put("summary", summary)
        put("sections", JSONArray(sections.map { it.toJson() }))
    }

    companion object {
        fun fromJson(raw: String): InteractivePlan? =
            runCatching { JSONObject(raw) }.getOrNull()?.let { fromJson(it) }

        fun fromJson(obj: JSONObject): InteractivePlan? {
            val array = obj.optJSONArray("sections") ?: return null
            val sections = mutableListOf<InteractiveSection>()
            for (i in 0 until array.length()) {
                val section = array.optJSONObject(i) ?: continue
                sections += parseSection(section, i)
            }
            if (sections.isEmpty()) return null
            return InteractivePlan(
                title = obj.optString("title").ifBlank { "Interactive workout" }.trim(),
                summary = obj.optString("summary").trim(),
                sections = sections,
            )
        }

        private fun parseSection(obj: JSONObject, index: Int): InteractiveSection {
            val exercises = mutableListOf<InteractiveExercise>()
            val exerciseArray = obj.optJSONArray("exercises")
            if (exerciseArray != null) {
                for (i in 0 until exerciseArray.length()) {
                    exerciseArray.optJSONObject(i)?.let { exercises += parseExercise(it, i) }
                }
            }
            val rounds = mutableListOf<InteractiveRound>()
            val roundArray = obj.optJSONArray("rounds")
            if (roundArray != null) {
                for (i in 0 until roundArray.length()) {
                    roundArray.optJSONObject(i)?.let { round ->
                        val parsed = parseRound(round, i)
                        if (parsed.movements.isNotEmpty()) rounds += parsed
                    }
                }
            }
            return InteractiveSection(
                title = obj.optString("title").ifBlank { "Section ${index + 1}" }.trim(),
                kind = normaliseKind(obj.optString("kind")),
                notes = parseNotes(obj.opt("notes")),
                metrics = parseMetrics(obj.optJSONArray("metrics")),
                exercises = exercises,
                rounds = rounds,
            )
        }

        /**
         * Notes are one block of text. Plans made while the app asked for a
         * list of rows still hold an array; its entries are joined back into
         * the paragraph they belong in.
         */
        private fun parseNotes(raw: Any?): String = when (raw) {
            is JSONArray -> (0 until raw.length())
                .map { raw.optString(it).trim().trimStart('-', '•', '*', '–', '—').trim() }
                .filter { it.isNotEmpty() }
                .joinToString(" ")
            is String -> raw.trim()
            else -> ""
        }

        private fun parseRound(obj: JSONObject, index: Int): InteractiveRound {
            val movements = mutableListOf<InteractiveMovement>()
            val array = obj.optJSONArray("movements")
            if (array != null) {
                for (i in 0 until array.length()) {
                    array.optJSONObject(i)?.let { movements += parseMovement(it, i) }
                }
            }
            return InteractiveRound(
                label = obj.optString("label").ifBlank { "Round ${index + 1}" }.trim(),
                notes = obj.optString("notes").trim(),
                movements = movements,
            )
        }

        private fun parseMovement(obj: JSONObject, index: Int): InteractiveMovement =
            InteractiveMovement(
                name = obj.optString("name")
                    .ifBlank { obj.optString("exercise") }
                    .ifBlank { "Movement ${index + 1}" }
                    .trim(),
                target = obj.optString("target")
                    .ifBlank { obj.optString("prescription") }
                    .trim(),
                notes = obj.optString("notes").trim(),
                metrics = parseMetrics(obj.optJSONArray("metrics")).ifEmpty {
                    listOf(MetricDef("result", "Result", MetricKind.TEXT))
                },
            )

        private fun parseExercise(obj: JSONObject, index: Int): InteractiveExercise {
            val sets = mutableListOf<InteractiveSet>()
            val setArray = obj.optJSONArray("sets")
            if (setArray != null) {
                for (i in 0 until setArray.length()) {
                    setArray.optJSONObject(i)?.let { sets += parseSet(it, i) }
                }
            }
            val metrics = parseMetrics(obj.optJSONArray("metrics"))
            val effectiveMetrics = metrics.ifEmpty {
                listOf(MetricDef("result", "Result", MetricKind.TEXT))
            }
            return InteractiveExercise(
                name = obj.optString("name")
                    .ifBlank { obj.optString("exercise") }
                    .ifBlank { "Exercise ${index + 1}" }
                    .trim(),
                notes = obj.optString("notes").trim(),
                metrics = effectiveMetrics,
                sets = if (sets.isEmpty()) {
                    listOf(InteractiveSet(label = "Result", target = ""))
                } else {
                    sets
                },
            )
        }

        private fun parseSet(obj: JSONObject, index: Int): InteractiveSet = InteractiveSet(
            label = obj.optString("label").ifBlank { "Set ${index + 1}" }.trim(),
            target = obj.optString("target")
                .ifBlank { obj.optString("prescription") }
                .trim(),
            metrics = parseMetrics(obj.optJSONArray("metrics")),
        )

        fun parseMetrics(array: JSONArray?): List<MetricDef> {
            if (array == null) return emptyList()
            val out = mutableListOf<MetricDef>()
            val used = mutableSetOf<String>()
            for (i in 0 until array.length()) {
                val obj = array.optJSONObject(i) ?: continue
                val kind = MetricKind.fromKey(
                    obj.optString("kind").ifBlank { obj.optString("type") }
                )
                val label = obj.optString("label")
                    .ifBlank { obj.optString("name") }
                    .ifBlank { kind.label }
                    .trim()
                val baseKey = slug(
                    obj.optString("key").ifBlank { label }.ifBlank { kind.key }
                )
                var key = baseKey
                var n = 2
                while (!used.add(key)) {
                    key = "${baseKey}_$n"
                    n++
                }
                out += MetricDef(
                    key = key,
                    label = label,
                    kind = kind,
                    unit = obj.optString("unit").ifBlank { defaultUnit(kind) },
                    hint = if (obj.isNull("hint")) "" else obj.optString("hint").trim(),
                )
            }
            return out
        }

        fun normaliseKind(raw: String): String = when (raw.lowercase(Locale.US).trim()) {
            "strength", "lift", "weightlifting" -> "strength"
            "metcon", "conditioning", "wod", "amrap", "emom", "for_time" -> "metcon"
            "accessory", "pump", "hyrox", "skill" -> "accessory"
            "rest" -> "rest"
            else -> "other"
        }

        private fun defaultUnit(kind: MetricKind): String = when (kind) {
            MetricKind.WEIGHT -> "kg"
            MetricKind.DISTANCE -> "m"
            MetricKind.CALORIES -> "cal"
            else -> ""
        }

        private fun slug(value: String): String =
            value.lowercase(Locale.US)
                .replace(Regex("[^a-z0-9]+"), "_")
                .trim('_')
                .ifBlank { "value" }
    }
}

